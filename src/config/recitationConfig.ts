/**
 * Merges the canonical 99-Names metadata (fetched from `public/data/namesOfAllah.json`
 * via `api/namesOfAllah/namesOfAllahClient.ts`) with the timestamp rows from
 * `data/namesTimestamps.json`, producing the fully-timed `AllahName[]` list in
 * canonical order. Name ids are the zero-padded `number` from the metadata.
 * A name with no timestamp row falls back to `0` (starts at the top of the audio).
 */
export function buildAllahNames(metadata: DivineName[]): AllahName[] {
  const timestampByNumber = new Map(
    NAMES_TIMESTAMPS.map((entry) => [Number.parseInt(entry.id, 10), entry.timestampSeconds]),
  );

  return metadata.map((name) => ({
    id: String(name.number).padStart(2, '0'),
    arabic: name.arabic,
    transliteration: name.transliteration,
    meaning: name.meaning,
    timestampSeconds: timestampByNumber.get(name.number) ?? 0,
  }));
}

/** URL shapes accepted by the Immersive Recitation media guard. */
const URL_PREFIX_PATTERNS = [/^\//, /^https?:\/\//i, /^data:/i, /^blob:/i];

/**
 * Phase 1 hardening — runtime config guard.
 *
 * Verifies every media URL in the ACTIVE config before it can ever reach a
 * `<video>` / `<audio>` element, so an empty/placeholder value fails loudly
 * HERE with the exact field named — instead of surfacing later as a generic
 * browser media error (often after a silent fetch failure). Runs once at app
 * start, development builds only (see src/index.tsx).
 *
 * Note: an absolute path like `/media/recitation/names-of-allah.mp3` passes
 * even though the file may not exist yet — that is the owner's job to add the
 * real assets (see the LICENSE NOTICE above). This guard catches malformed and
 * empty values, i.e. config mistakes.
 */
/**
 * Phase 2 — pure validation of the melodic-track schema fields.
 *
 * Separated from `assertValidRecitationConfig` so the shape rules are unit-
 * testable. `style`, `introSeconds`/`outroSeconds`, `durationSeconds` and the
 * interplay between them are checked here; URL/timestamp-row checks live in
 * their own validators.
 */
export interface ReciterShape {
  style: ReciterConfig['style'];
  introSeconds: number;
  outroSeconds: number;
  durationSeconds: number;
  timestamps: readonly TimestampEntry[];
  loop?: boolean;
}

export function validateReciterShape(reciter: ReciterShape): string[] {
  const problems: string[] = [];
  const label = 'ACTIVE_RECITER';
  const { style, introSeconds, outroSeconds, durationSeconds, timestamps, loop } = reciter;

  if (style !== 'nasheed' && style !== 'recitation') {
    problems.push(`${label}.style must be 'nasheed' or 'recitation', got ${JSON.stringify(style)}`);
  }
  if (loop !== undefined && typeof loop !== 'boolean') {
    problems.push(`${label}.loop must be a boolean (or omitted), got ${JSON.stringify(loop)}`);
  }
  const checkBookendSeconds = (field: 'introSeconds' | 'outroSeconds'): void => {
    const value = reciter[field];
    if (typeof value !== 'number' || !Number.isFinite(value) || value < 0) {
      problems.push(`${label}.${field} must be a finite non-negative number, got ${JSON.stringify(value)}`);
    }
  };
  checkBookendSeconds('introSeconds');
  checkBookendSeconds('outroSeconds');
  if (
    typeof durationSeconds !== 'number' ||
    !Number.isFinite(durationSeconds) ||
    durationSeconds <= 0
  ) {
    problems.push(`${label}.durationSeconds must be a finite positive number, got ${JSON.stringify(durationSeconds)}`);
  }
  if (
    Number.isFinite(introSeconds) &&
    Number.isFinite(outroSeconds) &&
    Number.isFinite(durationSeconds) &&
    introSeconds + outroSeconds >= durationSeconds
  ) {
    problems.push(
      `${label} intro+outro (${introSeconds}+${outroSeconds}) must be shorter than the full duration (${durationSeconds})`,
    );
  }
  // A nasheed opens with its instrumental intro: the first name may not begin
  // before `introSeconds`, and the last name must start before the outro.
  if (style === 'nasheed') {
    const first = timestamps[0];
    if (first && Number.isFinite(introSeconds) && first.timestampSeconds < introSeconds) {
      problems.push(
        `nasheed first name starts at ${first.timestampSeconds}s but introSeconds is ${introSeconds}s — the first name must not begin inside the intro`,
      );
    }
    const last = timestamps[timestamps.length - 1];
    if (last && Number.isFinite(outroSeconds) && Number.isFinite(durationSeconds)) {
      if (last.timestampSeconds >= durationSeconds - outroSeconds) {
        problems.push(
          `nasheed last name starts at ${last.timestampSeconds}s but must begin before the outro (${outroSeconds}s from the end, duration ${durationSeconds}s)`,
        );
      }
    }
  }

  return problems;
}

export function assertValidRecitationConfig(): void {
  const problems: string[] = [];

  const isNonEmptyUrlLike = (value: string): boolean =>
    value.trim().length > 0 && URL_PREFIX_PATTERNS.some((pattern) => pattern.test(value));

  const checkUrl = (label: string, value: string): void => {
    if (typeof value !== 'string' || value.trim().length === 0) {
      problems.push(`${label}: missing or empty — expected a non-empty path/URL string`);
    } else if (!isNonEmptyUrlLike(value)) {
      problems.push(`${label}: ${JSON.stringify(value)} does not look like a path/URL`);
    }
  };

  checkUrl(`ACTIVE_RECITER.audioUrl (reciter "${ACTIVE_RECITER.id}")`, ACTIVE_RECITER.audioUrl);
  problems.push(
    ...validateReciterShape({
      style: ACTIVE_RECITER.style,
      introSeconds: ACTIVE_RECITER.introSeconds,
      outroSeconds: ACTIVE_RECITER.outroSeconds,
      durationSeconds: ACTIVE_RECITER.durationSeconds,
      timestamps: ACTIVE_RECITER.timestamps,
      loop: ACTIVE_RECITER.loop,
    }),
  );
  problems.push(...validateTimestampEntries(ACTIVE_RECITER.timestamps));

  if (VIDEO_PLAYLIST.length === 0) {
    problems.push('VIDEO_PLAYLIST is empty');
  }
  for (const asset of VIDEO_PLAYLIST) {
    checkUrl(`VIDEO_PLAYLIST[${asset.id}].url`, asset.url);
    checkUrl(`VIDEO_PLAYLIST[${asset.id}].posterUrl`, asset.posterUrl);
  }

  if (problems.length > 0) {
    const message = [
      '[Immersive Recitation] Invalid media config — fix these before it reaches your UI:',
      `  - ${problems.join('\n  - ')}`,
      '(Thrown in development only — see src/index.tsx requirement for the dev-only invocation.)',
    ].join('');
    console.error(message);
    throw new Error(message);
  }
}

/**
 * Phase 4 — validates a final timestamp scheme (the output of the dev
 * timestamp editor) before it is wired into the synchronizer:
 * exactly 99 entries, ids strictly "01".."99" in order, and timestamps STRICTLY
 * ascending. Monotonicity is a hard invariant of the synchronizer; an unsorted
 * file would silently corrupt which name is shown. Returns a list of problems
 * (empty = valid).
 */
export function validateTimestampEntries(entries: readonly TimestampEntry[]): string[] {
  const problems: string[] = [];

  if (entries.length !== 99) {
    problems.push(`expected exactly 99 timestamp rows, found ${entries.length}`);
  }

  entries.forEach((entry, i) => {
    const expectedId = String(i + 1).padStart(2, '0');
    if (entry.id !== expectedId) {
      problems.push(`row ${i} has id "${entry.id}", expected "${expectedId}"`);
    }
    if (typeof entry.timestampSeconds !== 'number' || !Number.isFinite(entry.timestampSeconds)) {
      problems.push(`row "${entry.id}" has a non-number timestamp: ${JSON.stringify(entry.timestampSeconds)}`);
      return;
    }
    const previous = entries[i - 1];
    if (i > 0 && previous && entry.timestampSeconds <= previous.timestampSeconds) {
      problems.push(
        `row "${entry.id}" timestamp ${entry.timestampSeconds} is not strictly greater than the previous row (${previous.timestampSeconds}) — timestamps must be ascending`,
      );
    }
  });

  return problems;
}

/** True once the reachability check has run so it never spams the dev console. */
let audioReachabilityChecked = false;

/**
 * Phase 3 — dev-time reachability check for the recitation audio.
 *
 * At dev app start, sends ONE HEAD/GET request to assert the audio URL does
 * not 404 BEFORE the browser ever tries to play it (this is what should have
 * caught the placeholder value that 404'd before it hit the player). Uses HEAD;
 * falls back to a Range GET on servers that reject HEAD. Writes a clear
 * console.warn naming the URL and the expected destination. It is a WARNING
 * only — playback itself gracefully pauses on error (see useAudioEngine).
 */
export async function warnIfRecitationAudioMissing(): Promise<void> {
  if (typeof window === 'undefined' || process.env.NODE_ENV !== 'development') {
    return;
  }
  if (audioReachabilityChecked) {
    return;
  }
  audioReachabilityChecked = true;

  const url = ACTIVE_RECITER.audioUrl;
  try {
    let response: Response = await fetch(url, { method: 'HEAD', cache: 'no-cache' });
    if (response.status === 405 || response.status === 501) {
      // Some static servers reject HEAD — probe with a tiny Range GET instead.
      response = await fetch(url, { headers: { Range: 'bytes=0-0' }, cache: 'no-cache' });
    }
    if (!response.ok) {
      console.warn(
        `[Immersive Recitation] audioUrl "${url}" → HTTP ${response.status} ${response.statusText}. ` +
          `The 99-Names recitation file is not reachable. Drop it at public/audio/asma-ul-husna-full.mp3 ` +
          `(or repoint ACTIVE_RECITER.audioUrl to the licensed asset) or the immersive player will stay silent.`,
      );
    }
  } catch (error) {
    console.warn(
      `[Immersive Recitation] could not verify audioUrl "${url}" (${String(error)}). ` +
        `Check the value in ACTIVE_RECITER before shipping.`,
    );
  }
}